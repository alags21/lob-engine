def replace_block(path, name, body):
    s = open(path, newline="").read().replace("\r\n", "\n")
    pat = re.compile(rf"(<!-- BEGIN GENERATED:{name} -->\n).*?(<!-- END GENERATED:{name} -->)", re.S)
    if not pat.search(s):
        return None
    return pat.sub(lambda m: m.group(1) + body + "\n" + m.group(2), s)


