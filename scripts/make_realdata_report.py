#!/usr/bin/env python3
"""Generate docs/REALDATA.md and the `realdata` generated blocks in README.md / docs/RESULTS.md / docs/DESIGN.md
from the JSON summaries in bench/results/realdata/. No number in those places is typed by hand.

Inputs (all small, derived summaries; the raw Nasdaq file is never in the repository):
  scan_summary.json, validation_full.json, symbols_analysis.json, exp_{base,replace,xloses,group}.json, bench.json
Usage: python scripts/make_realdata_report.py [--check]
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RD = os.path.join(ROOT, "bench", "results", "realdata")
BUCKETS = ["pre_market", "continuous", "market_hours_other", "post_close"]


def load(name):
    p = os.path.join(RD, name)
    return json.load(open(p)) if os.path.exists(p) else None


def pct(a, b, d=2):
    return f"{100.0 * a / b:.{d}f}%" if b else "n/a"


def n(x):
    return f"{int(x):,}"


def hms(ns):
    s = ns / 1e9
    return f"{int(s // 3600):02d}:{int(s % 3600 // 60):02d}:{s % 60:09.6f}"


def dims_table(title, labels, dim):
    lines = [f"| {title} | executions checked | FIFO deviations | rate |", "|---|---|---|---|"]
    for lab, d in zip(labels, dim):
        if d["checked"]:
            lines.append(f"| {lab} | {n(d['checked'])} | {n(d['mismatched'])} | {pct(d['mismatched'], d['checked'])} |")
    return "\n".join(lines)


def headline_numbers(val, scan):
    t = val["total"]
    pc = t["priority_check"]["continuous"]
    viol = sum(t["violations"].values())
    return t, pc, viol


def build():
    val, scan, sym = load("validation_full.json"), load("scan_summary.json"), load("symbols_analysis.json")
    exps = {k: load(f"exp_{k}.json") for k in ("base", "replace", "xloses", "group")}
    bench = load("bench.json")
    if not val or not scan:
        sys.exit("missing validation_full.json or scan_summary.json")
    t, pc, viol = headline_numbers(val, scan)
    tax = t["continuous_same_price_mismatch_taxonomy"]
    mm = pc["mismatches"]
    out = {}

    # ---------------------------------------------------------------- headline block
    kinds = pc["mismatch_by_kind"]
    head = [
        f"Real Nasdaq ITCH 5.0 data, one trading day (30 July 2019), {n(val['decoded_messages'])} decoded messages across {n(val['symbols_seen'])} symbols "
        f"({n(scan['messages'])} frames in the file, 0 malformed). Every message was replayed through the engine; selected symbols were also run through the Stage 2 reference model.",
        "",
        "| check | result |",
        "|---|---|",
        f"| order-state violations (unknown/duplicate reference, over-execute, over-cancel, our size differs from the exchange's, rejected operation) | **{n(viol)}** |",
        f"| executions checked in continuous trading (engine picks the maker) | {n(pc['checked'])} |",
        f"| engine chose the exact order the exchange executed | {n(pc['engine_matched_exchange_choice'])} ({pct(pc['engine_matched_exchange_choice'], pc['checked'])}) |",
        f"| deviations from strict FIFO (a different order at the same price) | {n(kinds['same_price_other_order'])} ({pct(kinds['same_price_other_order'], pc['checked'])}) |",
        f"| price-priority violations (an order at a better price was skipped) | {n(kinds['better_priced_order_ahead'])} |",
        f"| executions where the engine found no fill | {n(kinds['no_fill'])} |",
        f"| reference-model comparisons (BBO, all levels, queue order) on {sum(1 for s in val['symbols'] if s['reference_model_compared'])} symbols | {n(t['reference_comparisons'])} comparisons, {n(t['reference_level_mismatches'] + t['reference_queue_order_mismatches'])} disagreements |",
    ]
    if bench:
        w, th, lat = bench["workload"], bench["throughput_ops_per_sec"], bench["latency_ns"]
        head += ["", f"Real-stream replay (pre-decoded, pinned, {bench['method']['measured_reps']} repetitions): {n(w['ops_replayed'])} engine operations over {w['books']} books, "
                 f"{th['median'] / 1e6:.2f} Mops/s median (CV {th['cv_pct']:.1f}%), p50 {lat['p50']['median']:.0f} ns, p99 {lat['p99']['median']:.0f} ns, p99.9 {lat['p99_9']['median']:.0f} ns."]
    out["headline"] = "\n".join(head)

    # ---------------------------------------------------------------- full doc
    d = []
    d.append("# Validation on real Nasdaq ITCH data (Stage 7)\n")
    d.append("<!-- Generated by scripts/make_realdata_report.py from bench/results/realdata/*.json. Do not edit by hand. -->\n")
    d.append("## Data and handling\n")
    d.append("- Input: Nasdaq TotalView-ITCH 5.0 sample `07302019.NASDAQ_ITCH50.gz` (30 July 2019), kept OUTSIDE the repository. Integrity: `gzip -t` passed and the size matched the expected "
             "3,662,140,094 bytes (no checksum file was available). The terms of the sample are unclear, so it is treated as not redistributable: the repository contains only counts, "
             "summary statistics and tiny excerpts (the small JSON files in `bench/results/realdata/`).")
    d.append("- Guards: `.gitignore` patterns, `scripts/check_repo_size.py` (CI step and optional pre-commit hook `scripts/hooks/pre-commit`: fails on files over 2 MB or on archive/ITCH-looking names).")
    d.append("- CI never uses Nasdaq data: the `itch-synthetic` job runs the parser, validator, reference cross-check and replay benchmark on a synthetic ITCH file generated by our own code (`lob_itch synth`).")
    d.append("- Spec: Nasdaq NQTV-ITCH 5.0. Messages S, R, H, A, F, E, C, X, D, U, P, Q are decoded; other types are skipped by their length prefix. "
             f"Skipped (unused) message types: {', '.join(f'{k}={n(v)}' for k, v in scan['messages_by_type'].items() if k not in 'SRHAFECXDUPQ')}.\n")
    d.append("## Result summary\n")
    d.append(out["headline"] + "\n")
    d.append("## Scan of the file\n")
    se = scan["system_events_first_ts_ns"]
    d.append(f"{n(scan['messages'])} messages, {n(scan['symbols'])} symbols, {n(scan['malformed'])} malformed, truncated final frame: {scan['truncated_final_frame']}. "
             f"System events (first occurrence, ns since midnight): market hours start `Q` at {n(se['Q'])} ({hms(se['Q'])}), end `M` at {n(se['M'])} ({hms(se['M'])}). "
             "Message counts by type: " + ", ".join(f"{k}: {n(v)}" for k, v in scan["messages_by_type"].items()) + ". "
             "Busiest symbols by message count: " + ", ".join(f"{s['symbol']} ({n(s['messages'])})" for s in scan["symbols_by_messages"][:8]) + ".\n")
    d.append("### How the symbols for the reference-model comparison were chosen\n")
    refs = [s["symbol"] for s in val["symbols"] if s["reference_model_compared"]]
    d.append(f"All {n(val['symbols_seen'])} symbols were validated for checks (a) and (b). The Stage 2 reference book (slow, O(n) per op) was run on {', '.join(refs)}: "
             "SPY (busiest by message count), AAPL and MSFT (named liquid stocks), TSLA (execution-heavy, mid-ranked), and SCHP (the symbol whose message count equals the median over all symbols: the thinly traded case).\n")
    d.append("## Mapping ITCH to the engine\n")
    d.append("""| ITCH | Engine operation |
|---|---|
| A / F | submit limit GTC (id = order reference, price in 1/10000 dollar = integer ticks). An add that would cross or lock our uncrossed book is counted and not inserted |
| D | cancel |
| X | partial cancel = `modify` down at the same price (keeps priority, the engine's modify rule); to zero = cancel |
| U | cancel + new order with the new reference (new queue position). Experiment `--replace-keeps-priority 1` keeps priority when the price is unchanged and the size does not increase |
| E / C | submit a marketable IOC on the opposite side at the executed order's price for the executed size; the ENGINE chooses the maker. Expected: exactly one trade against the executed reference at that price and size. C executions print at a different price from the order's, so the order's own price is used |
| P, Q | counted only (non-displayed and cross prints do not touch the displayed book) |
| S, H, Q(cross) | define the phase: before `S Q` pre-market, between `S Q` and `S M` market hours, after post-close. A symbol is in the continuous bucket when the phase is market hours, its trading state is `T`, it has had its opening cross and not its closing cross |
""")
    d.append("Why a pass of the priority check is meaningful: the IOC does not name the maker. If the engine's price-time rules, its modify rule or the replace handling differed from the "
             "exchange's for the book state built only from add/cancel/replace messages, the engine would hit a different order and the check fails; the unit tests contain such cases. "
             "A trivially echoing implementation could not fail; this one does, as the results show. After a disagreement the symbol's book is rebuilt from the exchange-implied state "
             "(arrival order) so one disagreement does not cascade.\n")
    d.append("Checks (all in `lob_itch validate`): (a) order-level consistency; (b) the engine-picks-the-maker priority check; (c) selected symbols also feed the Stage 2 reference book and BBO, "
             "every level aggregate and every queue order are compared every 5,000 per-symbol messages.\n")
    d.append("## Validation results (full day, final binary)\n")
    d.append("### By phase\n")
    d.append("| phase | executions checked | engine matched | deviations | same-price other order | better-priced ahead | no fill | adds that would cross our book |")
    d.append("|---|---|---|---|---|---|---|---|")
    for b in BUCKETS:
        x = t["priority_check"][b]
        k = x["mismatch_by_kind"]
        d.append(f"| {b} | {n(x['checked'])} | {n(x['engine_matched_exchange_choice'])} | {n(x['mismatches'])} ({pct(x['mismatches'], x['checked'])}) | {n(k['same_price_other_order'])} | {n(k['better_priced_order_ahead'])} | {n(k['no_fill'])} | {n(x['adds_that_would_cross_our_book'])} |")
    d.append("")
    d.append("Order-state violations: " + ", ".join(f"{k.replace('_', ' ')}: {n(v)}" for k, v in t["violations"].items()) +
             f". Message totals: adds {n(t['adds'])}, deletes {n(t['deletes'])}, partial cancels {n(t['partial_cancels'])}, replaces {n(t['replaces'])}, executions E {n(t['executions_E'])} and C {n(t['executions_C'])}, "
             f"non-cross trades P {n(t['trades_P'])}, crosses {n(t['crosses_Q'])}. Executions on orders that could not be booked: {n(t['events_on_unbooked_orders'])}. "
             f"Book rebuilds after a disagreement: {n(t['book_rebuilds_after_disagreement'])}; symbols hitting the rebuild cap: {n(val['symbols_diverged_rebuild_cap'])}.\n")
    d.append("### Reference-model cross-check and per-symbol rates\n")
    d.append("| symbol | reference model compared | continuous executions | FIFO deviations | rate | reference comparisons | reference disagreements |")
    d.append("|---|---|---|---|---|---|---|")
    for s in val["symbols"]:
        if not s["reference_model_compared"] and s is not val["symbols"][0] and val["symbols"].index(s) >= 10:
            continue
        c = s["stats"]["priority_check"]["continuous"]
        d.append(f"| {s['symbol']} | {'yes' if s['reference_model_compared'] else 'no'} | {n(c['checked'])} | {n(c['mismatches'])} | {pct(c['mismatches'], c['checked'])} | "
                 f"{n(s['stats']['reference_comparisons'])} | {n(s['stats']['reference_level_mismatches'] + s['stats']['reference_queue_order_mismatches'])} |")
    d.append("")
    if sym:
        q = sym["active_symbol_mismatch_rate_quantiles"]
        d.append(f"Across the {n(sym['symbols_with_at_least_200_continuous_executions'])} symbols with at least 200 continuous executions the per-symbol deviation rate has median {q['p50'] * 100:.2f}%, "
                 f"p90 {q['p90'] * 100:.2f}%, max {q['max'] * 100:.1f}%; {n(sym['symbols_with_zero_mismatches_among_active'])} of them have none. The top 10 symbols hold "
                 f"{sym['share_of_mismatches_in_top_10_symbols'] * 100:.1f}% and the top 100 hold {sym['share_of_mismatches_in_top_100_symbols'] * 100:.1f}% of all deviations. "
                 "Most deviating symbols: " + ", ".join(f"{s['symbol']} ({n(s['continuous_mismatched'])} of {n(s['continuous_checked'])})" for s in sym["top_symbols_by_mismatches"][:6]) + ".\n")

    # ---------------------------------------------------------------- hypotheses
    d.append("## Why does the exchange sometimes not follow strict FIFO? Hypotheses tested\n")
    d.append("The engine implements strict price-time priority and was NOT changed to make deviations disappear. Each hypothesis below is reported as supported, ruled out, partly tested or untestable from ITCH alone.\n")
    base, group, repl, xl = exps["base"], exps["group"], exps["replace"], exps["xloses"]

    def e_mm(e):
        return e["total"]["priority_check"]["continuous"]["mismatches"] if e else None

    def e_ck(e):
        return e["total"]["priority_check"]["continuous"]["checked"] if e else None
    if base:
        d.append(f"Experiment switches were run on the five reference symbols ({', '.join(refs)}) over the full day, "
                 f"{n(e_ck(base))} continuous executions checked in each run:\n")
        d.append("| engine/mapping variant | deviations | change vs baseline |")
        d.append("|---|---|---|")
        for key, label in (("base", "baseline mapping"), ("replace", "replace (U) at the same price with size not increased keeps priority"),
                           ("xloses", "partial cancel (X) loses priority"), ("group", "executions sharing a timestamp applied in queue order instead of feed order")):
            e = exps[key]
            if e:
                d.append(f"| {label} | {n(e_mm(e))} ({pct(e_mm(e), e_ck(e))}) | {'-' if key == 'base' else f'{100.0 * (e_mm(e) - e_mm(base)) / e_mm(base):+.1f}%'} |")
        d.append("")
    d.append("| # | hypothesis | status | evidence |")
    d.append("|---|---|---|---|")
    d.append(f"| 1 | Self-match prevention (exchange skips a same-participant same-price order) | **untestable from ITCH** | executions do not name the aggressor; only F orders carry an MPID, and only {n(tax['executed_order_is_attributed_F'])} executed and {n(tax['skipped_order_is_attributed_F'])} skipped orders among {n(mm)} deviations were F orders |")
    cdiff, ctot = t["C_price_differs_from_order"], t["executions_C"]
    d.append(f"| 2 | Pegged / repriced orders re-ranked without a visible U | **partly untestable** | ITCH has no price-change message other than U (handled). {n(cdiff)} of {n(ctot)} C executions print at a price different from the order's; E has no price field, so a silent reprice is not observable |")
    if sym and "spearman_mismatch_rate_vs_P_shares_per_executed_share" in sym:
        qs = sym["by_quartile_of_P_shares_per_executed_share"]
        d.append(f"| 3 | Non-displayed / reserve interest causes the deviations | **not supported by the proxy** | per-symbol deviation rate vs non-displayed-activity proxy (shares in P trades per displayed executed share): Spearman {sym['spearman_mismatch_rate_vs_P_shares_per_executed_share']:+.2f}; by quartile of the proxy the rate is "
                 + ", ".join(f"{q['rate'] * 100:.2f}%" for q in qs) + ". A proxy, not a measurement: hidden interest that never prints is invisible |")
    ah, ahr = tax["orders_ahead_of_executed_all_odd_lots"], tax["skipped_or_executed_by_remaining_size_odd"]["all_orders_ahead_odd_by_remaining"]
    d.append(f"| 4 | Odd-lot handling (odd lots lose priority to round lots) | **ruled out as the main cause** | in only {n(ah)} of {n(mm)} deviations ({pct(ah, mm)}) were all orders ahead of the executed one odd lots by original size ({n(ahr)}, {pct(ahr, mm)}, by remaining size); "
             f"the skipped order was an odd lot in {pct(tax['skipped_order_is_odd_lot'], mm)}, the executed one in {pct(tax['executed_order_is_odd_lot'], mm)}; both round lot in {pct(tax['both_round_lot'], mm)}. Round-lot size per symbol taken from the R message. Minimum-quantity rules are untestable |")
    dm = val["continuous_dimensions"]
    etp = dm["by_etp_flag_no_yes"]
    pr = dm["by_price_lt10usd_lt50_lt200_ge200"]
    d.append(f"| 5 | Time structure (hour, time since open, last 5 minutes, ETP vs stock, price, burst gap, after halt) | **structure found, not an explanation** | rate is {pct(etp[1]['mismatched'], etp[1]['checked'])} for ETPs vs {pct(etp[0]['mismatched'], etp[0]['checked'])} for other symbols and falls with price "
             f"({pct(pr[0]['mismatched'], pr[0]['checked'])} under $10 to {pct(pr[3]['mismatched'], pr[3]['checked'])} at $200 and over); see the tables below. Concentrated in a few symbols (top 10: {sym['share_of_mismatches_in_top_10_symbols'] * 100:.1f}% of deviations) |" if sym else "| 5 | Time structure | pending | |")
    if base and group:
        removed = e_mm(base) - e_mm(group)
        d.append(f"| 6 | Same-timestamp messages out of matching order | **supported for a minority** | applying executions that share a timestamp in queue order removes {n(removed)} of {n(e_mm(base))} deviations ({pct(removed, e_mm(base), 1)}) on the five reference symbols; "
                 f"{pct(tax['skipped_order_then_executed_within_1us'], mm)} of all deviations have the skipped order executed within 1 us. The feed's own sequence is what the engine replays |")
    d.append(f"| - | Replace keeps priority when price unchanged and size not increased | **{'ruled out' if repl and e_mm(repl) >= e_mm(base) else 'check'}** | {n(e_mm(repl))} vs {n(e_mm(base))} deviations on the reference symbols |" if repl and base else "")
    d.append(f"| - | Partial cancel (X) loses priority | **{'ruled out' if xl and e_mm(xl) >= e_mm(base) else 'check'}** | {n(e_mm(xl))} vs {n(e_mm(base))} deviations (more, not fewer) |" if xl and base else "")
    d.append(f"| - | Attributed (F) orders; orders created by replace | not explanatory | executed order created by replace in {pct(tax['executed_order_created_by_replace_U'], mm)} of deviations, skipped in {pct(tax['skipped_order_created_by_replace_U'], mm)} (replaces are common in the feed in general) |")
    d.append(f"| - | Fate of the skipped order | descriptive | later cancelled or modified {pct(tax['skipped_order_then_cancelled_or_modified'], mm)}, executed within 1 us {pct(tax['skipped_order_then_executed_within_1us'], mm)}, within 1 ms {pct(tax['skipped_order_then_executed_within_1ms'], mm)}, later {pct(tax['skipped_order_then_executed_later'], mm)}, still resting at the end {pct(tax['skipped_order_still_resting_at_end'], mm)} |")
    d.append(f"| - | Gap between the two orders' adds | descriptive | within 1 us {pct(tax['gap_between_the_two_adds_le_1us'], mm)}, 1 ms {pct(tax['gap_le_1ms'], mm)}, 1 s {pct(tax['gap_le_1s'], mm)}, over 1 s {pct(tax['gap_gt_1s'], mm)} (orders are mostly far apart in time, so this is not timestamp granularity) |")
    d = [x for x in d if x != ""] if False else d
    d.append("")
    d.append("### Quantified attribution and unexplained remainder\n")
    attr = []
    if base and group:
        attr.append(f"- Same-timestamp execution ordering: removes {pct(e_mm(base) - e_mm(group), e_mm(base), 1)} of deviations on the reference symbols (a measured effect of changing the replay order, not of changing the engine).")
    attr.append(f"- Odd-lot de-prioritisation: at most {pct(ah, mm, 1)} of deviations (all orders ahead odd lots), by original size; {pct(ahr, mm, 1)} by remaining size. This is an upper bound on what the hypothesis could explain, because the order ahead being odd is necessary, not sufficient.")
    if base and group:
        explained = (e_mm(base) - e_mm(group)) / e_mm(base) + ah / mm
        attr.append(f"- Even if the two effects were disjoint and fully additive, they would account for at most {100 * explained:.1f}% of deviations; **at least {100 * (1 - explained):.1f}% of the deviations are unexplained**.")
    attr.append(f"- {n(kinds['same_price_other_order'])} of the {n(mm)} continuous deviations were a different order at the same price; {n(kinds['better_priced_order_ahead'])} involved skipping a better-priced order; order-state violations: {n(viol)}.")
    ph = t["priority_check"]
    attr.append(f"- Deviation rate by phase: pre-market {pct(ph['pre_market']['mismatches'], ph['pre_market']['checked'], 2)}, continuous {pct(ph['continuous']['mismatches'], ph['continuous']['checked'], 2)}, "
                f"market hours outside the continuous window {pct(ph['market_hours_other']['mismatches'], ph['market_hours_other']['checked'], 2)}, post-close {pct(ph['post_close']['mismatches'], ph['post_close']['checked'], 2)}: deviations are concentrated in regular continuous trading.")
    d += attr
    d.append("")
    d.append("### Where the deviations are (continuous hours)\n")
    d.append(dims_table("hour of day (ET, hour starting)", [f"{h:02d}:00" for h in range(24)], dm["by_hour_of_day"]))
    d.append("")
    d.append(dims_table("time since the symbol's opening cross", ["< 1 s", "< 10 s", "< 60 s", "< 10 min", "later"], dm["by_time_since_symbol_opening_cross_lt1s_lt10s_lt60s_lt10min_rest"]))
    d.append("")
    d.append(dims_table("session end", ["before 15:55", "from 15:55"], dm["by_session_end_before_1555_from_1555"]))
    d.append("")
    d.append(dims_table("symbol type", ["non-ETP", "ETP"], dm["by_etp_flag_no_yes"]))
    d.append("")
    d.append(dims_table("order price", ["under $10", "$10-50", "$50-200", "$200 and over"], dm["by_price_lt10usd_lt50_lt200_ge200"]))
    d.append("")
    d.append(dims_table("gap since previous message of the symbol", ["< 10 us", "< 100 us", "< 1 ms", "1 ms or more"], dm["by_gap_since_previous_message_of_symbol_lt10us_lt100us_lt1ms_ge1ms"]))
    d.append("")
    d.append(dims_table("within 10 s after trading resumed after a halt", ["no", "yes"], dm["by_within_10s_after_trading_resume_no_yes"]))
    d.append("")
    d.append("### Interpretation\n")
    d.append(f"The engine's order-state tracking agrees with the exchange's exactly ({n(viol)} violations over {n(val['decoded_messages'])} messages), no execution ever skipped a better-priced order except {n(kinds['better_priced_order_ahead'])} "
             f"case(s), and in {pct(pc['engine_matched_exchange_choice'], pc['checked'], 1)} of {n(pc['checked'])} continuous-hours executions strict price-time priority picked the very order the exchange executed. "
             f"The remaining {pct(kinds['same_price_other_order'], pc['checked'], 1)} are executions of a different order at the same price. Real exchanges apply rules beyond strict FIFO "
             "(display priority over non-displayed interest, reserve-order replenishment, self-trade prevention, special order types, odd-lot rules), none of which the feed exposes; this is the likely home of the residual "
             "but it is not demonstrated here. A small part comes from the order in which the feed lists executions that share a timestamp. Describe the result as: zero order-state violations, "
             f"{pct(kinds['same_price_other_order'], pc['checked'], 1)} of executions deviate from strict FIFO at the same price, a minority attributable to feed ordering, the rest unexplained from public data.\n")

    # ---------------------------------------------------------------- benchmark
    if bench:
        d.append("## Real-stream replay benchmark\n")
        w, th, lat, env, m = bench["workload"], bench["throughput_ops_per_sec"], bench["latency_ns"], bench["environment"], bench["method"]
        d.append(f"Method: the ITCH stream is decoded once (decompression, parsing, bookkeeping and the engine, {w['decode_seconds_including_decompression']:.0f} s, NOT part of the measurement) while the exact "
                 f"operation stream applied to the engine for the selected symbols is recorded in memory; the timed replay then feeds that in-memory stream to fresh books ({m['model']}). "
                 f"{m['warmup_reps']} untimed warmup repetition and {m['measured_reps']} measured repetitions; throughput from whole-loop wall time without per-op timers, latency from per-op TSC timestamps "
                 f"({env['clock']['name']}, timestamp pair overhead {env['clock']['timestamp_pair_overhead_ns']:.0f} ns, not subtracted). The event callback only counts events and trades.\n")
        d.append(f"Environment: {env['cpu']} ({env['logical_cores']} logical cores), {env['os']}, flags `{env['flags']}`, thread pinned to logical CPU {env['pinned_cpu']} (efficiency class 1, see `bench/results/cpu_topology.txt`), "
                 f"CPU load measured before the run {env['cpu_load_percent_before_run']}%. {env['note']}\n")
        d.append(f"Workload: symbols {', '.join(w['symbols'])}; {n(w['itch_frames_read'])} frames read; {n(w['ops_replayed'])} engine operations over {w['books']} books "
                 f"({', '.join(f'{k.replace('_', ' ')}: {n(v)}' for k, v in w['ops_by_category'].items())}); {n(w['events'])} events, {n(w['trades'])} trades; {n(w['resting_orders_at_end'])} orders resting at the end. "
                 f"Final book digests equal to the validation run's: {w['final_book_digests_equal_to_validation_run']} of {w['final_book_digests_checked']} checked.\n")
